using System.Runtime.CompilerServices;
using System.Text;
using Beskar.Jobs.Client.Options;
using Beskar.Jobs.Common.Enums;
using Beskar.Jobs.Common.Interfaces;
using Beskar.Jobs.Common.Models;
using Beskar.Jobs.Common.Topics;
using Beskar.Memory.Results;
using Beskar.Memory.Results.Errors;
using Beskar.Mqtt.Common.Builders.Connecting;
using Beskar.Mqtt.Common.Builders.Disconnecting;
using Beskar.Mqtt.Common.Builders.Publishing;
using Beskar.Mqtt.Common.Interfaces;
using Beskar.Mqtt.Protocol.Enums;

namespace Beskar.Jobs.Client;

/// <summary>
/// High-level client for submitting jobs, registering recurring Cron schedules, triggering cooperative cancellations,
/// and streaming real-time job status updates over MQTT.
/// </summary>
public sealed class JobClient : IAsyncDisposable
{
   private readonly bool _ownsMqttClient;
   private int _disposed;

   public IMqttClient MqttClient { get; }
   public JobClientOptions Options { get; }

   public bool IsConnected => MqttClient.IsConnected;

   public JobClient(IMqttClient mqttClient, JobClientOptions? options = null, bool ownsMqttClient = true)
   {
      ArgumentNullException.ThrowIfNull(mqttClient);
      MqttClient = mqttClient;
      Options = options ?? new JobClientOptions();
      _ownsMqttClient = ownsMqttClient;
   }

   /// <summary>
   /// Connects the underlying MQTT client to the configured broker endpoint if not already connected.
   /// </summary>
   public async ValueTask<VoidResult<StringError>> ConnectAsync(CancellationToken ct = default)
   {
      if (MqttClient.IsConnected)
      {
         return new VoidResult<StringError>();
      }

      if (Options.EndPoint is null)
      {
         return new StringError("JobClientOptions.EndPoint must be configured when connecting an unconnected IMqttClient.");
      }

      var connectOptions = new ConnectOptions
      {
         EndPoint = Options.EndPoint,
         ProtocolVersion = MqttProtocolVersion.V50,
         ClientIdUtf8Bytes = Encoding.UTF8.GetBytes(Options.ClientId),
         CleanSession = true
      };

      var result = await MqttClient.ConnectAsync(connectOptions, ct);
      if (result.Failed)
      {
         return result.Error;
      }

      return new VoidResult<StringError>();
   }

   /// <summary>
   /// Gracefully disconnects the underlying MQTT client if owned by this instance.
   /// </summary>
   public async ValueTask DisconnectAsync(CancellationToken ct = default)
   {
      if (_ownsMqttClient && MqttClient.IsConnected)
      {
         await MqttClient.DisconnectAsync(new DisconnectOptions(), ct);
      }
   }

   /// <summary>
   /// Enqueues a job for immediate or delayed execution and awaits scheduler confirmation.
   /// </summary>
   public async Task<Result<EnqueueJobResponse, StringError>> EnqueueAsync<TArgs>(
      string jobType,
      TArgs args,
      string queue = "default",
      TimeSpan? delay = null,
      int maxAttempts = 3,
      TimeSpan? timeout = null,
      string? parentJobId = null,
      Dictionary<string, string>? metadata = null,
      string? jobId = null,
      CancellationToken ct = default)
   {
      ArgumentException.ThrowIfNullOrWhiteSpace(jobType);
      ArgumentException.ThrowIfNullOrWhiteSpace(queue);

      var now = DateTimeOffset.UtcNow;
      var scheduledAt = delay is { TotalMilliseconds: > 0 } d ? now.Add(d) : now;

      var request = new EnqueueJobRequest
      {
         JobId = jobId ?? $"job-{Guid.NewGuid():N}",
         JobType = jobType,
         Queue = queue,
         Payload = Options.Serializer.Serialize(args),
         ScheduledAtUtc = scheduledAt,
         MaxAttempts = Math.Max(1, maxAttempts),
         Timeout = timeout,
         ParentJobId = parentJobId,
         Metadata = metadata
      };

      return await SendEnqueueRequestAsync(request, ct);
   }

   /// <summary>
   /// Enqueues a job using compile-time metadata generated by <c>[GeneratedJobHandler]</c>.
   /// </summary>
   public Task<Result<EnqueueJobResponse, StringError>> EnqueueGeneratedAsync<THandler, TArgs>(
      TArgs args,
      TimeSpan? delay = null,
      int maxAttempts = 3,
      TimeSpan? timeout = null,
      string? parentJobId = null,
      Dictionary<string, string>? metadata = null,
      string? jobId = null,
      CancellationToken ct = default)
      where THandler : IGeneratedJobDescriptor, IJobHandler<TArgs>
   {
      return EnqueueAsync(
         THandler.GeneratedJobType,
         args,
         THandler.GeneratedQueue,
         delay,
         maxAttempts,
         timeout,
         parentJobId,
         metadata,
         jobId,
         ct);
   }

   /// <summary>
   /// Enqueues a child continuation job that automatically executes once <paramref name="parentJobId"/> succeeds.
   /// </summary>
   public Task<Result<EnqueueJobResponse, StringError>> EnqueueContinuationAsync<TArgs>(
      string parentJobId,
      string jobType,
      TArgs args,
      string queue = "default",
      int maxAttempts = 3,
      TimeSpan? timeout = null,
      Dictionary<string, string>? metadata = null,
      CancellationToken ct = default)
   {
      ArgumentException.ThrowIfNullOrWhiteSpace(parentJobId);
      return EnqueueAsync(
         jobType,
         args,
         queue,
         delay: null,
         maxAttempts: maxAttempts,
         timeout: timeout,
         parentJobId: parentJobId,
         metadata: metadata,
         ct: ct);
   }

   /// <summary>
   /// Registers or updates a recurring Cron or interval job schedule with the scheduler.
   /// </summary>
   public async Task<Result<ScheduleRecurringJobResponse, StringError>> ScheduleRecurringAsync<TArgs>(
      string recurringJobId,
      string cronExpression,
      string jobType,
      TArgs args,
      string queue = "default",
      MisfirePolicy misfirePolicy = MisfirePolicy.FireOnceNow,
      OverlapPolicy overlapPolicy = OverlapPolicy.SkipIfRunning,
      int maxAttempts = 3,
      TimeSpan? timeout = null,
      CancellationToken ct = default)
   {
      ArgumentException.ThrowIfNullOrWhiteSpace(recurringJobId);
      ArgumentException.ThrowIfNullOrWhiteSpace(cronExpression);
      ArgumentException.ThrowIfNullOrWhiteSpace(jobType);

      var request = new ScheduleRecurringJobRequest
      {
         RecurringJobId = recurringJobId,
         CronExpression = cronExpression,
         JobType = jobType,
         Queue = queue,
         Payload = Options.Serializer.Serialize(args),
         MisfirePolicy = misfirePolicy,
         OverlapPolicy = overlapPolicy,
         MaxAttempts = Math.Max(1, maxAttempts),
         Timeout = timeout
      };

      var payloadBytes = Options.Serializer.Serialize(request);
      var rpcResult = await MqttClient.RequestAsync(
         JobTopics.RecurringCommandTopic,
         payloadBytes,
         Options.RequestTimeout,
         ct);

      if (rpcResult.Failed)
      {
         return rpcResult.Error;
      }

      var response = Options.Serializer.Deserialize<ScheduleRecurringJobResponse>(rpcResult.Success.Payload.Span);
      if (response is null)
      {
         return new StringError("Failed to deserialize ScheduleRecurringJobResponse from scheduler.");
      }

      if (!response.Accepted)
      {
         return new StringError(response.ErrorMessage ?? "Recurring job schedule rejected by scheduler.");
      }

      return response;
   }

   /// <summary>
   /// Publishes a cooperative cancellation command for the specified job to both the scheduler and active worker.
   /// </summary>
   public async Task<VoidResult<StringError>> CancelJobAsync(
      string jobId,
      string? reason = null,
      CancellationToken ct = default)
   {
      ArgumentException.ThrowIfNullOrWhiteSpace(jobId);

      var command = new JobCancelCommand
      {
         JobId = jobId,
         Reason = reason ?? "Cancelled by client request",
         TimestampUtc = DateTimeOffset.UtcNow
      };

      var topicBytes = JobTopics.FormatCancelCommandToBytes(jobId);
      var payloadBytes = Options.Serializer.Serialize(command);

      var publishOptions = PublishOptions.Create()
         .WithTopic(topicBytes)
         .WithPayload(payloadBytes)
         .WithQualityOfService(QualityOfServiceType.AtLeastOnce)
         .Build();

      var pubResult = await MqttClient.PublishAsync(publishOptions, ct);
      if (pubResult.Failed)
      {
         return pubResult.Error;
      }

      return new VoidResult<StringError>();
   }

   /// <summary>
   /// Streams real-time status and progress updates for <paramref name="jobId"/> over MQTT.
   /// Because status updates are published as retained messages, late subscribers immediately receive the current state.
   /// </summary>
   public async IAsyncEnumerable<JobStatusUpdate> WatchJobStatusAsync(
      string jobId,
      bool stopOnTerminal = true,
      [EnumeratorCancellation] CancellationToken ct = default)
   {
      ArgumentException.ThrowIfNullOrWhiteSpace(jobId);

      var statusTopic = JobTopics.FormatStatus(jobId);
      var stream = MqttClient.SubscribeStream(
         statusTopic,
         bytes => Options.Serializer.Deserialize<JobStatusUpdate>(bytes.Span),
         QualityOfServiceType.AtLeastOnce,
         ct: ct);

      await foreach (var update in stream)
      {
         if (update is null)
         {
            continue;
         }

         yield return update;

         if (stopOnTerminal && update.IsTerminal)
         {
            yield break;
         }
      }
   }

   /// <summary>
   /// Awaits the terminal <see cref="JobStatusUpdate"/> (<c>Succeeded</c>, <c>Failed</c>, <c>Cancelled</c>, or <c>DeadLettered</c>)
   /// for the specified <paramref name="jobId"/>.
   /// </summary>
   public async Task<Result<JobStatusUpdate, StringError>> WaitForJobCompletionAsync(
      string jobId,
      TimeSpan timeout = default,
      CancellationToken ct = default)
   {
      ArgumentException.ThrowIfNullOrWhiteSpace(jobId);

      using var timeoutCts = timeout > TimeSpan.Zero
         ? CancellationTokenSource.CreateLinkedTokenSource(ct)
         : null;

      if (timeoutCts is not null)
      {
         timeoutCts.CancelAfter(timeout);
      }

      var effectiveCt = timeoutCts?.Token ?? ct;

      try
      {
         await foreach (var update in WatchJobStatusAsync(jobId, stopOnTerminal: true, effectiveCt))
         {
            if (update.IsTerminal)
            {
               return update;
            }
         }

         return new StringError($"Status stream for job '{jobId}' ended before reaching a terminal state.");
      }
      catch (OperationCanceledException) when (!ct.IsCancellationRequested)
      {
         return new StringError($"Timed out waiting for job '{jobId}' to complete after {timeout.TotalMilliseconds:F0}ms.");
      }
   }

   /// <summary>
   /// Awaits completion of <paramref name="jobId"/> and deserializes its <typeparamref name="TResult"/> payload if it succeeded.
   /// </summary>
   public async Task<Result<TResult?, StringError>> WaitForJobResultAsync<TResult>(
      string jobId,
      TimeSpan timeout = default,
      CancellationToken ct = default)
   {
      var completionResult = await WaitForJobCompletionAsync(jobId, timeout, ct);
      if (completionResult.Failed)
      {
         return completionResult.Error;
      }

      var finalStatus = completionResult.Success;
      if (finalStatus.Status != JobStatus.Succeeded)
      {
         return new StringError(
            $"Job '{jobId}' did not succeed (Status: {finalStatus.Status}, Error: {finalStatus.ErrorMessage ?? finalStatus.Message ?? "none"}).");
      }

      if (finalStatus.ResultPayload is null || finalStatus.ResultPayload.Length == 0)
      {
         return default(TResult);
      }

      return Options.Serializer.Deserialize<TResult>(finalStatus.ResultPayload);
   }

   private async Task<Result<EnqueueJobResponse, StringError>> SendEnqueueRequestAsync(
      EnqueueJobRequest request,
      CancellationToken ct)
   {
      var payloadBytes = Options.Serializer.Serialize(request);
      var rpcResult = await MqttClient.RequestAsync(
         JobTopics.EnqueueCommandTopic,
         payloadBytes,
         Options.RequestTimeout,
         ct);

      if (rpcResult.Failed)
      {
         return rpcResult.Error;
      }

      var response = Options.Serializer.Deserialize<EnqueueJobResponse>(rpcResult.Success.Payload.Span);
      if (response is null)
      {
         return new StringError("Failed to deserialize EnqueueJobResponse from scheduler.");
      }

      if (!response.Accepted)
      {
         return new StringError(response.ErrorMessage ?? "Job enqueue request was rejected by scheduler.");
      }

      return response;
   }

   public async ValueTask DisposeAsync()
   {
      if (Interlocked.Exchange(ref _disposed, 1) != 0)
      {
         return;
      }

      if (_ownsMqttClient)
      {
         await DisconnectAsync();
         await MqttClient.DisposeAsync();
      }
   }
}
