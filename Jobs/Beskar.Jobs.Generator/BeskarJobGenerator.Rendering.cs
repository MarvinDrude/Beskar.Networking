using System.Text;
using Beskar.Memory.Code;
using Microsoft.CodeAnalysis;
using Microsoft.CodeAnalysis.CSharp;
using Microsoft.CodeAnalysis.Text;

namespace Beskar.Jobs.Generator;

public partial class BeskarJobGenerator
{
   private static void GenerateSourceForType(SourceProductionContext spc, GeneratedJobHandlerModel model)
   {
      if (model.IsErrorTypeNotPartial)
      {
         spc.ReportDiagnostic(Diagnostic.Create(
            TargetTypeMustBePartial,
            model.TypeLocation.ToLocation(),
            model.ErrorNonPartialTypeName));
         return;
      }

      if (model.IsErrorInvalidJobType)
      {
         spc.ReportDiagnostic(Diagnostic.Create(
            InvalidJobType,
            model.TypeLocation.ToLocation(),
            model.TypeName));
         return;
      }

      if (model.IsErrorInvalidQueue)
      {
         spc.ReportDiagnostic(Diagnostic.Create(
            InvalidQueueName,
            model.TypeLocation.ToLocation(),
            model.TypeName));
         return;
      }

      if (model.IsErrorMissingInterface)
      {
         spc.ReportDiagnostic(Diagnostic.Create(
            MissingJobHandlerInterface,
            model.TypeLocation.ToLocation(),
            model.TypeName));
         return;
      }

      var generatedBody = GenerateDescriptorMembers(model);
      if (string.IsNullOrEmpty(generatedBody)) return;

      Span<char> initialBuffer = stackalloc char[512];
      var writer = new CodeTextWriter(initialBuffer, stackalloc char[64]);

      try
      {
         writer.WriteLine("// <auto-generated/>");
         writer.WriteLine("#nullable enable");
         writer.WriteLine();

         var hasNamespace = !string.IsNullOrEmpty(model.NamespaceName);
         if (hasNamespace)
         {
            writer.WriteLineInterpolated($"namespace {model.NamespaceName}");
            writer.OpenBody();
         }

         foreach (var type in model.NestingTypes)
         {
            writer.WriteLineInterpolated($"partial {type.TypeKind} {type.Name}");
            writer.OpenBody();
         }

         writer.WriteLineInterpolated($"{model.Accessibility} partial {model.TypeKind} {model.TypeName} : global::Beskar.Jobs.Common.Interfaces.IGeneratedJobDescriptor");
         writer.OpenBody();

         writer.Write(generatedBody, true);

         writer.CloseBody();

         for (var i = 0; i < model.NestingTypes.Length; i++) writer.CloseBody();

         if (hasNamespace) writer.CloseBody();

         var typePrefix = model.NestingTypes.Length > 0
            ? string.Join("_", model.NestingTypes.Select(t => t.Name)) + "_" + model.TypeName
            : model.TypeName;

         var rawHint = string.IsNullOrEmpty(model.NamespaceName)
            ? typePrefix
            : $"{model.NamespaceName}_{typePrefix}";
         var safeHint = new string([.. rawHint.Select(c => char.IsLetterOrDigit(c) ? c : '_')]);
         var hintName = $"{safeHint}.BeskarJob.g.cs";

         spc.AddSource(hintName, SourceText.From(writer.ToString(), Encoding.UTF8));
      }
      finally
      {
         writer.Dispose();
      }
   }

   private static string GenerateDescriptorMembers(GeneratedJobHandlerModel model)
   {
      Span<char> initialBuffer = stackalloc char[512];
      var writer = new CodeTextWriter(initialBuffer, stackalloc char[64]);

      try
      {
         var escapedJobType = SymbolDisplay.FormatLiteral(model.JobType, true);
         var escapedQueue = SymbolDisplay.FormatLiteral(model.Queue, true);

         writer.WriteLineInterpolated($"public const string JobType = {escapedJobType};");
         writer.WriteLineInterpolated($"public const string DefaultQueue = {escapedQueue};");
         writer.WriteLine("public static string GeneratedJobType => JobType;");
         writer.WriteLine("public static string GeneratedQueue => DefaultQueue;");

         return writer.ToString();
      }
      finally
      {
         writer.Dispose();
      }
   }
}
